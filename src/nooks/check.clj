(ns nooks.check
  "bb check: build the site as of each date in docs/plan.md § Checks and fail
  on any broken invariant.

  The scan is regex-based: babashka has no HTML parser built in, and every page
  is generated by us (hiccup or quickblog), so tag shapes are predictable. A
  check that can't see something passes it silently, so each check is also
  exercised against a violating snippet in test/nooks/check_test.clj.

  Not yet checked, because the pages they guard aren't built yet: day-page gate
  contents and gate text (day pages land in the next PR)."
  (:require [babashka.fs :as fs]
            [clojure.java.shell :as shell]
            [clojure.string :as str]
            [nooks.build :as build]
            [nooks.data :as data]
            [nooks.denylist :as deny]
            [nooks.layout :as layout]
            [nooks.state :as state]))

(def dates
  ["2026-11-30" "2026-12-01T04:59Z" "2026-12-01T05:00Z" "2026-12-04T04:59Z"
   "2026-12-04T05:00Z" "2026-12-07" "2026-12-11" "2026-12-18" "2026-12-23" "2027-01-15"])

(def forbidden-words
  ["immutable" "functional" "data-oriented" "concurrent" "fast" "productive" "expressive" "scalable"])

;; ---- Helpers ---------------------------------------------------------------

(defn- strip-tags [s] (str/replace s #"<[^>]*>" ""))

(defn- external? [u] (boolean (re-find #"^(?i)(https?:)?//" u)))

(defn- skip-link? [u]
  (or (str/blank? u) (str/starts-with? u "#") (re-find #"^(?i)(mailto|tel|data|javascript):" u)))

(defn- attr-values
  "Values of attribute `attr` on tags matching `tag-re` (both double-quoted)."
  [html tag-re attr]
  (for [tag (re-seq (re-pattern (str "<(?:" tag-re ")\\b[^>]*>")) html)
        :let [[_ v] (re-find (re-pattern (str "\\s" attr "=\"([^\"]*)\"")) tag)]
        :when v]
    (str/replace v "&amp;" "&")))

(defn- page-url
  "The URL path a file is served at, e.g. /powertools-and-parens/start/."
  [base out-dir f]
  (let [rel (str/replace (str (fs/relativize out-dir f)) java.io.File/separator "/")]
    (str base "/" (str/replace rel #"(^|/)index\.html$" "$1"))))

(defn- target-file
  "The file a site path resolves to, or nil if it's outside the base path."
  [base out-dir path]
  (let [path (-> path (str/replace #"[?#].*$" ""))]
    (when (or (= path base) (str/starts-with? path (str base "/")))
      (let [rel (subs path (count base))
            rel (if (or (str/blank? rel) (str/ends-with? rel "/")) (str rel "index.html") rel)]
        (fs/path out-dir (str/replace rel #"^/" ""))))))

;; ---- Checks: each returns a seq of problem strings for one page ------------

(defn- check-primary [_ctx html]
  (let [n (count (re-seq #"class=\"(?:[^\"]*\s)?pill(?:\s[^\"]*)?\"" html))]
    (when (not= 1 n) [(str n " primary buttons (want exactly 1)")])))

(defn- check-external-loads [_ctx html]
  (concat
   (for [u (concat (attr-values html "script|img|iframe|source|video|audio|embed|track" "src")
                   (attr-values html "link" "href"))
         :when (external? u)
         ;; <link rel=alternate> (the feed) doesn't load anything.
         :when (not (re-find (re-pattern (str "rel=\"alternate\"[^>]*href=\"" (java.util.regex.Pattern/quote u))) html))]
     (str "loads a third-party URL on page load: " u))
   (when (re-find #"(?i)<style|\sstyle=\"" html)
     ["inline style (blocked by the CSP)"])
   (when (re-find #"(?i)<script(?![^>]*\ssrc=)[^>]*>" html)
     ["inline script (blocked by the CSP)"])))

(defn- check-csp-origins
  "The CSP names no off-site origin but YouTube's no-cookie frames and, when
  :analytics/goatcounter is set, that one GoatCounter site. Adding a tracker
  means editing this list on purpose, not just the policy (docs/analytics.md)."
  [{:keys [site]} html]
  (let [allowed (set (remove nil? ["https://www.youtube-nocookie.com" (layout/analytics-origin site)]))
        ;; Attribute order isn't fixed (hiccup puts content= first), so find
        ;; the tag, then read its content.
        tag     (some #(when (str/includes? % "http-equiv=\"Content-Security-Policy\"") %)
                      (re-seq #"<meta\b[^>]*>" html))
        policy  (some->> tag (re-find #"\scontent=\"([^\"]*)\"") second)]
    (if-not policy
      ["no Content-Security-Policy <meta>"]
      (for [o (distinct (re-seq #"https?://[^\s;]+" policy))
            :when (not (allowed o))]
        (str "CSP allows an off-site origin that isn't on the list: " o)))))

(defn- strip-comments
  "HTML with <!-- … --> removed. A link inside a comment isn't followable, e.g.
  the author notes a blog post carries into the blog index's excerpt. Only the
  link and anchor checks use this: comments still ship in the page source, so
  the name and host checks read them."
  [html]
  (str/replace html #"(?s)<!--.*?-->" ""))

(defn- check-links [{:keys [base out-dir file]} html]
  (let [html (strip-comments html)
        here (java.net.URI. (page-url base out-dir file))
        refresh (for [[_ u] (re-seq #"http-equiv=\"refresh\"[^>]*content=\"\d+;\s*url=([^\"]+)\"" html)] u)
        refresh2 (for [[_ u] (re-seq #"content=\"\d+;\s*url=([^\"]+)\"[^>]*http-equiv=\"refresh\"" html)] u)]
    (for [u (concat (attr-values html "a|link" "href")
                    (attr-values html "script|img|source" "src")
                    refresh refresh2)
          :when (not (skip-link? u))
          :when (not (external? u))
          :let [path (.getPath (.resolve here (str/replace u " " "%20")))
                f (target-file base out-dir path)]
          :when (or (nil? f) (not (fs/regular-file? f)))]
      (str "broken internal link: " u (when (nil? f) (str " (outside " base "/)"))))))

(defn- check-anchors
  "Every same-page link (<a href=\"#x\">) has an element with id=\"x\". Catches a
  table-of-contents entry left behind when a heading is renamed."
  [_ctx html]
  (let [html (strip-comments html)
        ids  (set (map second (re-seq #"\sid=\"([^\"]+)\"" html)))]
    (for [tag (re-seq #"<a\b[^>]*>" html)
          :let [[_ frag] (re-find #"\shref=\"#([^\"]+)\"" tag)]
          :when (and frag (not (ids frag)))]
      (str "in-page link to a missing anchor: #" frag))))

(defn- check-template-gate [{:keys [site]} html]
  (when (and (not (:template/public? site)) (str/includes? html "clojure-template-aoc"))
    ["links the template repo while :template/public? is false"]))

(defn- check-guests [{:keys [unconfirmed]} html]
  (for [g unconfirmed :when (str/includes? (strip-tags html) g)]
    (str "names an unconfirmed guest: " g)))

(defn- check-unannounced
  "An unannounced session's title (\"Session 03 · Demo\") must not appear: its
  row is a veil until :announced? is true."
  [{:keys [unannounced]} html]
  (for [title unannounced :when (str/includes? (strip-tags html) title)]
    (str "shows an unannounced session: " title)))

(defn- unannounced-titles
  "English titles of sessions not yet :announced?, as the shop list would print them."
  [{:keys [days i18n]}]
  (let [en (:en i18n)]
    (for [day days
          :let [{fmt :format :keys [n announced?]} (:day/session day)]
          :when (not announced?)]
      (format (:session/title en) (format "%02d" n)
              (get en (keyword "format" (name fmt)))))))

(defn- check-forbidden-words [_ctx html]
  (let [texts (concat (map second (re-seq #"(?s)<h[1-3]\b[^>]*>(.*?)</h[1-3]>" html))
                      (map second (re-seq #"(?s)<[a-z]+[^>]*class=\"[^\"]*\bchip\b[^\"]*\"[^>]*>(.*?)</" html)))]
    (for [t texts
          :let [t (str/lower-case (strip-tags t))]
          w forbidden-words
          :when (re-find (re-pattern (str "\\b" (java.util.regex.Pattern/quote w) "\\b")) t)]
      (str "feature word \"" w "\" in a heading or chip: " (str/trim t)))))

(defn- check-no-employer
  "Jordan, 2026-11-24: the employer is never named anywhere on the site; the
  role reads \"Software Engineer, Clojure Team\". Checks the whole HTML,
  attributes and URLs included, case-insensitively, against the hashed names
  in nooks.denylist."
  [{:keys [names] :or {names deny/names}} html]
  (when (pos? (deny/names-found html names))
    ["names the employer; use \"Software Engineer, Clojure Team\""]))

(defn- check-internal-links
  "No links to workplace tools (wikis, chat workspaces, shared docs)."
  [_ctx html]
  (for [h (deny/internal-hosts html)] (str "links an internal tool: " h)))

(defn- check-img-svg [_ctx html]
  (concat
   (for [tag (re-seq #"<img\b[^>]*>" html) :when (not (re-find #"\salt=\"" tag))]
     (str "img without alt: " tag))
   (for [tag (re-seq #"<svg\b[^>]*>" html) :when (not (re-find #"aria-hidden=\"true\"" tag))]
     (str "svg without aria-hidden=\"true\": " tag))))

(defn- check-lang [{:keys [out-dir file]} html]
  (let [rel (str (fs/relativize out-dir file))
        want (if (str/starts-with? rel "pt-br") "pt-BR" "en")]
    (when-not (re-find (re-pattern (str "<html lang=\"" want "\"")) html)
      [(str "<html> should have lang=\"" want "\"")])))

(def page-checks
  [check-primary check-external-loads check-csp-origins check-links check-anchors check-template-gate
   check-guests check-unannounced check-forbidden-words check-no-employer check-internal-links check-img-svg check-lang])

;; ---- Site-wide checks ------------------------------------------------------

(defn- check-twins [{:keys [out-dir]} files]
  (for [f files
        :let [rel (str/replace (str (fs/relativize out-dir f)) java.io.File/separator "/")]
        :when (not (re-find #"^(pt-br|blog)/|^404\.html$" rel))
        :when (not (fs/exists? (fs/path out-dir "pt-br" rel)))]
    (str rel ": no /pt-br/ twin")))

(defn- preview-posts []
  (for [f (fs/glob "blog/posts" "*.md")
        :when (re-find #"(?mi)^preview:\s*true\s*$" (first (str/split (slurp (str f)) #"\n\s*\n" 2)))]
    (str/replace (str (fs/file-name f)) #"\.md$" ".html")))

(defn- check-previews [{:keys [out-dir]}]
  (for [post (preview-posts)
        listing (concat ["blog/index.html" "blog/archive.html" "blog/atom.xml" "blog/planetclojure.xml"]
                        (map #(str (fs/relativize out-dir %)) (fs/glob (fs/path out-dir "blog" "tags") "*.html")))
        :let [f (fs/path out-dir listing)]
        :when (and (fs/exists? f) (str/includes? (slurp (str f)) post))]
    (str listing ": lists preview post " post)))

(defn- check-css [{:keys [out-dir]}]
  (for [f (fs/glob out-dir "**.css")
        [_ u] (re-seq #"url\(\s*[\"']?([^\"')]+)" (slurp (str f)))
        :when (external? u)]
    (str (fs/relativize out-dir f) ": loads a third-party URL: " u)))

;; ---- Runner ----------------------------------------------------------------

(defn check-site
  "Problems in a built site, as [file problem] pairs."
  [out-dir]
  (let [d     (data/load-all)
        site  (:site d)
        base  (:site/base-path site)
        unconfirmed (for [day (:days d) g (get-in day [:day/session :guests])
                          :when (not (:confirmed? g))] (:name g))
        files (sort (map str (fs/glob out-dir "**.html")))
        ctx   {:base base :out-dir out-dir :site site :unconfirmed unconfirmed
               :unannounced (unannounced-titles d)}]
    {:pages (count files)
     :problems
     (concat
      (for [f files
            :let [html (slurp f)
                  c (assoc ctx :file f)]
            chk page-checks
            p (chk c html)]
        [(str (fs/relativize out-dir f)) p])
      (map (fn [p] ["(site)" p]) (concat (check-twins ctx files) (check-previews ctx) (check-css ctx))))}))

;; ---- Repo-wide checks ------------------------------------------------------
;; The page checks only see built HTML. The repo is public too, so its tracked
;; files and commit messages get the same name and internal-host checks.

(def ^:private binary-ext #"(?i)\.(woff2?|ttf|otf|png|jpe?g|gif|ico|webp|pdf)$")

(def ^:private host-list-files
  "Files that name internal-tool hosts on purpose: the deny-list itself, the
  tests that feed it violating input, and temper's link-check schema."
  #{"src/nooks/denylist.clj" "test/nooks/check_test.clj" "docs/metadata-schema.edn"})

(defn- git-lines [& args]
  (let [{:keys [exit out]} (apply shell/sh "git" args)]
    (when (zero? exit) (str/split-lines out))))

(defn check-repo
  "Problems in tracked files and in the messages of commits reachable from HEAD,
  as [where problem] pairs."
  []
  (concat
   (for [f (git-lines "ls-files")
         :when (and (not (str/blank? f)) (not (re-find binary-ext f)) (fs/regular-file? f))
         :let [text (slurp f)]
         p (concat (when (pos? (deny/names-found text)) ["names the employer"])
                   (when-not (host-list-files f)
                     (for [h (deny/internal-hosts text)] (str "links an internal tool: " h))))]
     [f p])
   (let [{:keys [out]} (shell/sh "git" "log" "--format=%h%x00%B%x01")]
     (for [entry (str/split out #"\x01")
           :let [[sha msg] (str/split (str/trim entry) #"\x00" 2)]
           :when msg
           p (concat (when (pos? (deny/names-found msg)) ["names the employer"])
                     (for [h (deny/internal-hosts msg)] (str "links an internal tool: " h)))]
       [(str "commit " sha) p]))))

(defn -main [& _]
  (let [repo (doall (check-repo))
        _    (println (format "%-18s %s" "repo" (if (empty? repo) "ok" (str (count repo) " problem(s)"))))
        _    (doseq [[f p] repo] (println "   " f "—" p))
        results
        (doall
         (for [date dates]
           (let [out  (str (fs/path ".work" "check" (str/replace date ":" "")))
                 _    (build/build! {:as-of (state/parse-as-of date) :out-dir out
                                     :work-dir (str out "-work") :quiet? true})
                 {:keys [pages problems]} (check-site out)]
             (println (format "%-18s %3d pages  %s" date pages
                              (if (empty? problems) "ok" (str (count problems) " problem(s)"))))
             (doseq [[f p] (take 30 problems)] (println "   " f "—" p))
             (when (> (count problems) 30) (println "    …and" (- (count problems) 30) "more"))
             (count problems))))
        total (reduce + (count repo) results)]
    (println (if (zero? total)
               (str "bb check: all " (count dates) " dates pass")
               (str "bb check: " total " problem(s)")))
    (System/exit (if (zero? total) 0 1))))
